def test_expired_rotated_and_missing_admin_credentials_fail_closed(client, monkeypatch):
    login(client)
    token = client.cookies.get(access.COOKIE)
    key = next(iter(access.SESSIONS))
    expiry, version = access.SESSIONS[key]
    access.SESSIONS[key] = (time.time() - 1, version)
    assert not access.is_admin(token)
    access.SESSIONS[key] = (expiry, version)
    monkeypatch.setattr(access, "credentials", lambda: ("only-admin", "changed"))
    assert not access.is_admin(token)
    monkeypatch.setattr(access, "credentials", lambda: ("admin", ""))
    assert login(client).status_code == 503
    assert client.post("/api/reset", json={}).status_code == 403


