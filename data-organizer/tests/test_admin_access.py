def test_rate_limit_and_cross_site_login(client):
    body = {"email": "only-admin", "password": "wrong"}
    assert client.post("/api/admin/login", json=body, headers={"Origin": "https://other.example"}).status_code == 403
    for _ in range(5):
        assert client.post("/api/admin/login", json=body).status_code == 401
